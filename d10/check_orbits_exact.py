#!/usr/bin/env python3
"""Dimension ten: symmetry orbits of the 3,040 vectors and 1,136 candidate bases, and exact orthogonality
of the candidate bases that consist of 20th roots of unity.

Part A (numerical matching, as stated in the report): the group generated by cyclic shift, modulation, index
dilation x_j -> x_{aj} (a = 3, 7, 9), complex conjugation and the Fourier transform permutes the stored list of
3,040 vectors (as rays, first coordinate 1) and the 1,136 candidate bases.  Orbits are counted with union-find.

Part B (exact; rational arithmetic in Q[x]/Phi_20(x), no floating point in the decisive steps): the coordinates of
the vectors of three symmetry orbits (240 vectors) are identified as elements of the cyclotomic field Q(zeta_20)
from the 40-digit list (upstream_mub10/data/exact/bu10hp_unimod.txt) with PSLQ; the identification is only a guess,
and everything after it is exact: for these exact vectors z the script checks
(0) |z_j|^2 = 1 exactly, and z is within 1e-32 of the stored 40-digit point,
(1) unbiasedness to the Fourier basis: |sum_j zeta_10^{jk} z_j|^2 = 10 exactly for k = 0..9,
(2) pairwise orthogonality sum_j z_j conj(w_j) = 0 exactly for all 45 pairs of every candidate basis made of them.
Each exact vector solves the unbiasedness equations exactly and lies within 1e-32 of a stored center whose certified
box (half-width 1e-30, certify_roots.py and check_d10.py) contains exactly one root, so it is that root; hence these candidate bases are orthonormal
bases (after scaling by 1/sqrt 10), not only candidates.
"""
import json, os, sys
import numpy as np
from fractions import Fraction
from mpmath import mp, mpf, mpc, pi, cos, expj, pslq
HERE = os.path.dirname(os.path.abspath(__file__)) + "/"
ok = True
def check(name, cond, detail=""):
    global ok
    print(("[PASS] " if cond else "[FAIL] ") + name + (": " + str(detail) if detail != "" else "")); ok = ok and bool(cond)

V = np.load(HERE + "vecs.npy"); B = [tuple(sorted(b)) for b in json.load(open(HERE + "bases.json"))]
N, d = V.shape; assert (N, d) == (3040, 10) and len(B) == 1136
V = V / V[:, :1]
# ---------------- Part A: orbits ----------------
from scipy.spatial import cKDTree
def key(X): return np.concatenate([X.real, X.imag], axis=1)
tree = cKDTree(key(V))
w = np.exp(2j * np.pi / 10); idx = np.arange(10)
F = w ** np.outer(idx, idx)
gens = {"shift": lambda X: np.roll(X, -1, axis=1), "modulation": lambda X: X * (w ** idx)[None, :],
        "conjugation": lambda X: X.conj(), "Fourier": lambda X: X @ F.T}
for a in (3, 7, 9): gens["dilation %d" % a] = (lambda a: (lambda X: X[:, (a * idx) % 10]))(a)
perms = {}; worst = 0.0
for nm, g in gens.items():
    Y = g(V); Y = Y / Y[:, :1]
    dist, j = tree.query(key(Y)); worst = max(worst, dist.max())
    assert sorted(j.tolist()) == list(range(N)), nm + " is not a permutation of the list"
    perms[nm] = j
check("each generator permutes the 3,040 vectors", True, "largest matching distance %.2e" % worst)
def orbits(n, maps):
    p = list(range(n))
    def f(x):
        while p[x] != x: p[x] = p[p[x]]; x = p[x]
        return x
    for m in maps:
        for i in range(n): p[f(i)] = f(int(m[i]))
    cls = {}
    for i in range(n): cls.setdefault(f(i), []).append(i)
    orbits.classes = list(cls.values())
    return sorted((len(c) for c in cls.values()), reverse=True)
vo = orbits(N, perms.values()); vclasses = orbits.classes
check("vector orbits", len(vo) == 10, "%d orbits, sizes %s" % (len(vo), vo))
bidx = {b: i for i, b in enumerate(B)}; bperms = []
for nm, j in perms.items():
    img = [bidx.get(tuple(sorted(int(j[v]) for v in b))) for b in B]
    assert None not in img, nm + " does not map candidate bases to candidate bases"
    bperms.append(img)
bo = orbits(len(B), bperms)
check("candidate-basis orbits", len(bo) == 19, "%d orbits, sizes %s" % (len(bo), bo))
st = json.load(open(HERE + "upstream_mub10/data/exact/d10_analysis.json"))
check("orbit sizes agree with the stored analysis", sorted(st["orbit_sizes"], reverse=True) == vo and sorted(st["basis_orbit_sizes"], reverse=True) == bo)
# ---------------- Part B: exact orthogonality ----------------
mp.dps = 50
rows = [l.split() for l in open(HERE + "upstream_mub10/data/exact/bu10hp_unimod.txt")]
assert len(rows) == N
def hp(i):
    x = [mpf(t) for t in rows[i][1:19]]
    return [mpc(1)] + [mpc(x[2 * k], x[2 * k + 1]) for k in range(9)]
for i in range(3): assert max(abs(complex(t) - V[i][k]) for k, t in enumerate(hp(i))) < 1e-12, "row order differs from vecs.npy"
def red(ec):                                 # element of Q[x]/Phi_20 from {exponent: coefficient}; Phi_20 = x^8 - x^6 + x^4 - x^2 + 1
    c = [Fraction(0)] * 10
    for e, k in ec.items():
        e %= 20
        if e >= 10: c[e - 10] -= k           # x^10 = -1
        else: c[e] += k
    for t in (9, 8):                         # x^8 = x^6 - x^4 + x^2 - 1
        k = c[t]; c[t] = Fraction(0)
        for s_, q in ((t - 2, 1), (t - 4, -1), (t - 6, 1), (t - 8, -1)): c[s_] += k * q
    return c[:8]
def mul(a, b):
    out = {}
    for i, x in enumerate(a):
        if x:
            for j, y in enumerate(b):
                if y: out[i + j] = out.get(i + j, 0) + x * y
    return red(out)
def add(a, b): return [x + y for x, y in zip(a, b)]
def conj(a): return red({(-i) % 20: x for i, x in enumerate(a) if x})
def const(q): return [Fraction(q)] + [Fraction(0)] * 7
XP = lambda e: red({e: Fraction(1)})
C1 = add(XP(1), XP(19)); CP = [const(1), C1, mul(C1, C1), mul(C1, mul(C1, C1))]     # powers of c = 2 cos(pi/10)
I_ = XP(5)
cnum = 2 * cos(pi / 10); cb = [mpf(1), cnum, cnum ** 2, cnum ** 3]
zeta = expj(2 * pi / 20)
def real_elem(r):                            # guess r as a rational combination of 1, c, c^2, c^3
    if abs(r) < mpf(10) ** -35: return const(0)
    rel = pslq([r] + cb, maxcoeff=10 ** 7, maxsteps=20000)
    if not rel or rel[0] == 0: return None
    out = const(0)
    for k in range(4): out = add(out, [Fraction(-rel[k + 1], rel[0]) * t for t in CP[k]])
    return out
def elem(z):
    a, b = real_elem(z.real), real_elem(z.imag)
    if a is None or b is None: return None
    return add(a, mul(b, I_))
def value(e): return sum(mpf(q.numerator) / q.denominator * zeta ** k for k, q in enumerate(e))
exact = {}
for cl in vclasses:
    if any(elem(t) is None for t in hp(cl[0])): continue          # orbit not recognized in Q(zeta_20): skipped
    for i in cl:
        z = hp(i); E = [elem(t) for t in z]
        assert None not in E, "orbit only partly recognized"
        exact[i] = E
        assert max(abs(value(e) - t) for e, t in zip(E, z)) < mpf(10) ** -32
ONE, TEN, ZERO = const(1), const(10), const(0)
check("coordinates recognized in Q(zeta_20), each within 1e-32 of the stored 40-digit point", len(exact) > 0, "%d vectors in %d orbits" % (len(exact), sum(1 for cl in vclasses if cl[0] in exact)))
check("exact unimodularity |z_j|^2 = 1 (unbiased to I)", all(mul(e, conj(e)) == ONE for E in exact.values() for e in E))
def fsum(E, k):
    s_ = ZERO
    for j in range(10): s_ = add(s_, mul(XP(2 * j * k), E[j]))
    return s_
check("exact unbiasedness to the Fourier basis", all(mul(s_, conj(s_)) == TEN for E in exact.values() for s_ in [fsum(E, k) for k in range(10)]))
exact_bases = [b for b in B if all(v in exact for v in b)]
CE = {i: [conj(e) for e in E] for i, E in exact.items()}
def ip(u, v):
    s_ = ZERO
    for j in range(10): s_ = add(s_, mul(exact[u][j], CE[v][j]))
    return s_
orth = all(ip(u, v) == ZERO for b in exact_bases for a_, u in enumerate(b) for v in b[a_ + 1:])
check("exact pairwise orthogonality inside each candidate basis made of these vectors", orth, "%d bases, %d pairs" % (len(exact_bases), 45 * len(exact_bases)))
check("number of candidate bases proved to be orthonormal bases exactly", len(exact_bases) == 96, len(exact_bases))
print("OK" if ok else "FAILED"); sys.exit(0 if ok else 1)
